begin;
lock table public.invoices, public.payments in share row exclusive mode;
select pg_advisory_xact_lock(617203581);
create temporary table integrity_install on commit drop as
    select to_regclass('public.integrity_ledger') is null as initialize;

create table if not exists public.integrity_ledger (
    id bigint generated by default as identity primary key,
    seq_no bigint not null unique check (seq_no > 0),
    entity_type varchar(10) not null check (entity_type in ('invoice','payment')),
    entity_id integer not null check (entity_id > 0),
    event_type varchar(20) not null check (event_type in ('issued','voided','payment_recorded','adjustment')),
    canonical_payload text not null,
    prev_hash varchar(64) not null,
    current_hash varchar(64) not null unique,
    created_at timestamptz not null default now()
);
create index if not exists ix_integrity_entity on public.integrity_ledger(entity_type, entity_id);
create table if not exists public.integrity_verifications (
    id bigint generated by default as identity primary key,
    checked_at timestamptz not null default now(),
    checked_by varchar(40) not null,
    status varchar(12) not null check (status in ('valid','compromised')),
    total_records_checked bigint not null check (total_records_checked >= 0),
    first_broken_seq_no bigint,
    first_broken_entity_type varchar(10),
    first_broken_entity_id integer,
    failure_reason varchar(32),
    details jsonb not null default '{}'
);
alter table public.integrity_ledger enable row level security;
alter table public.integrity_verifications enable row level security;
revoke all on public.integrity_ledger, public.integrity_verifications from public, anon, authenticated, service_role;
revoke all on public.integrity_ledger, public.integrity_verifications
    from public, anon, authenticated, service_role, ferrepro_backend;
grant select, insert on public.integrity_ledger, public.integrity_verifications to ferrepro_backend;
grant select on public.integrity_ledger, public.integrity_verifications to service_role;
revoke all on sequence public.integrity_ledger_id_seq, public.integrity_verifications_id_seq
    from public, anon, authenticated, service_role, ferrepro_backend;
grant usage on sequence public.integrity_ledger_id_seq, public.integrity_verifications_id_seq to ferrepro_backend;
grant update(status) on public.invoices to ferrepro_backend;
drop policy if exists server_append on public.integrity_ledger;
create policy server_append on public.integrity_ledger for insert to ferrepro_backend with check (true);
drop policy if exists server_read on public.integrity_ledger;
create policy server_read on public.integrity_ledger for select to ferrepro_backend using (true);
drop policy if exists server_append on public.integrity_verifications;
create policy server_append on public.integrity_verifications for insert to ferrepro_backend with check (true);
drop policy if exists server_read on public.integrity_verifications;
create policy server_read on public.integrity_verifications for select to ferrepro_backend using (true);

create or replace function pg_temp.integrity_json(fields jsonb) returns text language sql immutable as $$
    select '{' || string_agg(to_json(key)::text || ':' || value::text, ',' order by key collate "C") || '}'
    from jsonb_each(fields)
$$;

-- Sellar el estado existente una sola vez. Reaplicar nunca repara un historial alterado.
do $$
declare
    doc record;
    seq bigint := 0;
    previous text := 'GENESIS';
    payload text;
    hash_value text;
begin
    if not (select initialize from integrity_install) then return; end if;
    for doc in
        select * from (
            select 'invoice' as kind, id, created_at, 'issued' as event,
                jsonb_build_object('invoice_number', invoice_number, 'order_id', order_id,
                    'employee_id', employee_id, 'subtotal', subtotal::text, 'shipping_cost', shipping_cost::text,
                    'tax_amount', tax_amount::text, 'discount_amount', discount_amount::text,
                     'total_amount', total_amount::text, 'status', status,
                    'created_at', to_char(created_at at time zone 'UTC','YYYY-MM-DD"T"HH24:MI:SS.US"Z"'),
                    'items_sha256', encode(sha256(convert_to(coalesce((
                        select string_agg(pg_temp.integrity_json(jsonb_build_object('id', i.id, 'name', i.name,
                            'product_id', i.product_id, 'quantity', i.quantity, 'sku', i.sku,
                            'subtotal', i.subtotal::text, 'unit_price', i.unit_price::text)) || chr(10),
                            '' order by i.id)
                        from public.invoice_items i where i.invoice_id = invoices.id
                    ), ''), 'UTF8')), 'hex')) as fields
            from public.invoices
            union all
            select 'payment', id, created_at, 'payment_recorded',
                jsonb_build_object('invoice_id', invoice_id, 'order_id', order_id, 'amount', amount::text,
                    'payment_method', payment_method,  'status', status, 'receipt_path', receipt_path,
                    'receipt_type', receipt_type, 'receipt_sha256', encode(sha256(receipt_data),'hex'),
                    'paid_at', to_char(paid_at at time zone 'UTC','YYYY-MM-DD"T"HH24:MI:SS.US"Z"'),
                    'created_at', to_char(created_at at time zone 'UTC','YYYY-MM-DD"T"HH24:MI:SS.US"Z"'))
            from public.payments
        ) docs order by created_at, kind, id
    loop
        seq := seq + 1;
        payload := pg_temp.integrity_json(doc.fields);
        hash_value := encode(sha256(convert_to(concat_ws('|', seq, doc.kind, doc.id, doc.event, payload, previous),
            'UTF8')), 'hex');
        insert into public.integrity_ledger(seq_no, entity_type, entity_id, event_type, canonical_payload,
            prev_hash, current_hash) values (seq, doc.kind, doc.id, doc.event, payload, previous, hash_value);
        previous := hash_value;
    end loop;
end $$;
commit;
