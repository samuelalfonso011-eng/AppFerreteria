begin;
set local search_path=public, pg_catalog;
create table if not exists public.ml_model_runs (
    id integer generated by default as identity primary key,
    model_name varchar(32) not null check (model_name in ('fraud_classifier','demand_regressor')),
    version varchar(32) not null,
    trained_at timestamptz not null default now(),
    artifact_path text not null,
    seed integer not null,
    dataset_summary jsonb not null,
    metrics jsonb not null,
    unique(model_name,version)
);
create table if not exists public.fraud_predictions (
    id integer generated by default as identity primary key,
    order_id integer references public.orders(id),
    invoice_id integer references public.invoices(id),
    payment_id integer references public.payments(id),
    model_run_id integer not null references public.ml_model_runs(id),
    fraud_probability double precision not null check (fraud_probability between 0 and 1),
    predicted_label varchar(12) not null check (predicted_label in ('normal','fraudulenta')),
    feature_snapshot jsonb not null,
    created_at timestamptz not null default now()
);
create index if not exists ix_fraud_predictions_order_id on public.fraud_predictions(order_id);
create index if not exists ix_fraud_predictions_invoice_id on public.fraud_predictions(invoice_id);
create index if not exists ix_fraud_predictions_payment_id on public.fraud_predictions(payment_id);
create index if not exists ix_fraud_predictions_model_run_id on public.fraud_predictions(model_run_id);
alter table public.ml_model_runs enable row level security;
alter table public.fraud_predictions enable row level security;
revoke all on public.ml_model_runs, public.fraud_predictions from public, anon, authenticated, service_role, ferrepro_backend;
grant select, insert on public.ml_model_runs, public.fraud_predictions to ferrepro_backend;
grant select on public.ml_model_runs, public.fraud_predictions to service_role;
revoke all on sequence public.ml_model_runs_id_seq, public.fraud_predictions_id_seq from public, anon, authenticated, service_role;
grant usage on sequence public.ml_model_runs_id_seq, public.fraud_predictions_id_seq to ferrepro_backend;
drop policy if exists server_access on public.ml_model_runs;
create policy server_access on public.ml_model_runs to ferrepro_backend using(true) with check(true);
drop policy if exists server_access on public.fraud_predictions;
create policy server_access on public.fraud_predictions to ferrepro_backend using(true) with check(true);
commit;
