begin;

alter table public.users drop constraint if exists check_user_role;
alter table public.users add constraint check_user_role
    check (role in ('admin', 'employee', 'customer'));

alter table public.orders
    add column if not exists customer_id integer references public.users(id) on delete set null,
    add column if not exists employee_id integer references public.users(id) on delete set null,
    add column if not exists channel varchar(12) not null default 'web';
alter table public.orders drop constraint if exists check_order_channel;
alter table public.orders add constraint check_order_channel
    check (channel in ('presencial', 'web', 'app', 'domicilio'));
create index if not exists ix_orders_customer_id on public.orders(customer_id);
create index if not exists ix_orders_employee_id on public.orders(employee_id);

create table if not exists public.invoices (
    id integer generated by default as identity primary key,
    invoice_number integer generated always as (id) stored not null unique,
    order_id integer not null unique references public.orders(id),
    employee_id integer references public.users(id) on delete set null,
    subtotal numeric(14, 2) not null,
    shipping_cost numeric(14, 2) not null,
    tax_amount numeric(14, 2) not null,
    discount_amount numeric(14, 2) not null,
    total_amount numeric(14, 2) not null,
    status varchar(10) not null default 'emitida',
    created_at timestamptz not null default now(),
    constraint uq_invoice_id_order unique (id, order_id),
    constraint check_invoice_status check (status in ('emitida', 'anulada')),
    constraint check_invoice_amounts check (
        subtotal >= 0 and shipping_cost >= 0 and tax_amount >= 0
        and discount_amount between 0 and subtotal
        and total_amount = round(subtotal + shipping_cost + tax_amount - discount_amount, 2)
    )
);
create index if not exists ix_invoices_employee_id on public.invoices(employee_id);

create table if not exists public.invoice_items (
    id integer generated by default as identity primary key,
    invoice_id integer not null references public.invoices(id),
    product_id integer not null references public.products(id),
    name varchar(200) not null,
    sku varchar(50) not null,
    quantity integer not null,
    unit_price numeric(14, 2) not null,
    subtotal numeric(14, 2) not null,
    constraint check_invoice_item_amounts check (
        quantity > 0 and unit_price >= 0 and subtotal = round(quantity * unit_price, 2)
    )
);
create index if not exists ix_invoice_items_invoice_id on public.invoice_items(invoice_id);
create index if not exists ix_invoice_items_product_id on public.invoice_items(product_id);

create table if not exists public.payments (
    id integer generated by default as identity primary key,
    invoice_id integer not null,
    order_id integer not null references public.orders(id),
    amount numeric(14, 2) not null,
    payment_method varchar(15) not null,
    receipt_type varchar(20),
    receipt_data bytea,
    receipt_path text generated always as (
        case when receipt_type is not null then '/api/payments/' || cast(id as text) || '/receipt' end
    ) stored,
    status varchar(10) not null,
    paid_at timestamptz,
    created_at timestamptz not null default now(),
    foreign key (invoice_id, order_id) references public.invoices(id, order_id),
    constraint check_payment_amount check (amount > 0),
    constraint check_payment_method check (payment_method in ('efectivo', 'tarjeta', 'transferencia', 'pse', 'nequi')),
    constraint check_payment_status check (status in ('pendiente', 'aprobado', 'rechazado', 'anulado')),
    constraint check_payment_receipt check (
        (receipt_data is null and receipt_type is null) or
        (receipt_data is not null and receipt_type is not null
         and receipt_type in ('application/pdf', 'image/png', 'image/jpeg')
         and length(receipt_data) between 1 and 5242880)
    )
);
create index if not exists ix_payments_invoice_id on public.payments(invoice_id);
create index if not exists ix_payments_order_id on public.payments(order_id);

-- Flask usa sesiones propias. Ningún rol de la Data API recibe acceso a facturación.
do $$ begin
    if not exists (select from pg_roles where rolname = 'ferrepro_backend') then
        create role ferrepro_backend login;
    end if;
end $$;
grant usage on schema public to ferrepro_backend;

-- Los permisos de admin y empleado se verifican en Flask. Los comprobantes son privados.
alter table public.invoices enable row level security;
alter table public.invoice_items enable row level security;
alter table public.payments enable row level security;
revoke all on public.invoices, public.invoice_items, public.payments
    from public, anon, authenticated, service_role;
revoke all on sequence public.invoices_id_seq, public.invoice_items_id_seq, public.payments_id_seq
    from public, anon, authenticated, service_role;
grant select, insert on public.invoices, public.invoice_items, public.payments to ferrepro_backend;
grant usage on sequence public.invoices_id_seq, public.invoice_items_id_seq, public.payments_id_seq
    to ferrepro_backend;
drop policy if exists server_access on public.invoices;
create policy server_access on public.invoices to ferrepro_backend using (true) with check (true);
drop policy if exists server_access on public.invoice_items;
create policy server_access on public.invoice_items to ferrepro_backend using (true) with check (true);
drop policy if exists server_access on public.payments;
create policy server_access on public.payments to ferrepro_backend using (true) with check (true);

commit;
