def translate(key: str, lang: str = 'es', default: str = None) -> str:
    """Retorna la traducción para la clave solicitada en el idioma actual."""
    lang_dict = TRANSLATIONS.get(lang, TRANSLATIONS['es'])
    return lang_dict.get(key, default or key)


def translate_category(name: str, lang: str = 'es') -> str:
    """Traduce el nombre de una categoría estándar si existe en el diccionario."""
    cat_entry = CATEGORY_TRANSLATIONS.get(name)
    if cat_entry and lang in cat_entry:
        return cat_entry[lang]
    return name
